#!/usr/bin/env bash
# Build the firmware with arduino-cli against the Arduino ESP32 core.
#
# Decided on 2026-09-02: the project moves to the Arduino core. See
# docs/toolchain-arduino-cli.md. The consequence is that G1, G3 and G5 were
# measured against a build that this one replaces, and have to be taken again
# before they can be cited.
#
# There is no second copy of the firmware. `firmware/main/` stays the single
# source, and this script assembles a sketch from it on every run, because a
# forked copy would drift from the ESP-IDF build within a week and the two
# would disagree without anyone noticing. The sketch directory under
# build/arduino/ is generated output and is not edited by hand.
#
# Three things reconcile a native IDF application with a sketch:
#
#   1. `app_main` is renamed to `evpil_app_main` by a -D, not by editing
#      main.c, because the Arduino core supplies its own app_main and calls
#      setup(). The generated .ino calls it from setup().
#   2. The build switches ride in `compiler.{c,cpp}.extra_flags`, which are
#      empty hooks in the core's platform.txt. Overriding `build.extra_flags`
#      instead would drop the core's own USB defines and break the link.
#   3. The optimisation level is forced to -O2. The core builds at -Os and the
#      IDF build used CONFIG_COMPILER_OPTIMIZATION_PERF, and -Os would move
#      G1 and G5 for a reason that has nothing to do with the port.
#
# What this build cannot reproduce from sdkconfig.defaults: WiFi and Bluetooth
# are compiled into the core and cannot be configured out. Neither is started,
# so no radio transmits, but the image and the memory map differ from the IDF
# build's. That is one of the reasons the gates need re-measuring rather than
# transferring.
#
#   ./scripts/arduino_build.sh                              plain build
#   ./scripts/arduino_build.sh -DFAULT_INJECT=1             fault injection
#   ./scripts/arduino_build.sh -DFALLBACK_ENABLED=0         ablation A4
#   ./scripts/arduino_build.sh --flash                      build then flash
#   ./scripts/arduino_build.sh --flash -DFAULT_INJECT=1     both
#
# Any -D argument is passed through to the compiler unchanged, so the switch
# names are the same ones firmware/main/CMakeLists.txt documents.

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SRC="$ROOT/firmware/main"
# Deliberately outside the repository. The project directory has a space in
# its name, and arduino-cli word-splits --build-property values, so an -I
# pointing into the repo arrives at the compiler as two broken paths. This is
# the same class of problem that scripts/idf.sh exists to work around.
WORK="${EVPIL_ARDUINO_DIR:-$HOME/.cache/evpil-arduino}"
SKETCH="$WORK/evpil_fw"
BUILD_PATH="$WORK/out"
PORT="${EVPIL_PORT:-/dev/cu.usbmodem1101}"

# Matched to firmware/sdkconfig.defaults wherever the core allows it:
# 240 MHz, hardware USB CDC/JTAG (the console the link speaks over), PSRAM
# off, and the 8 MB flash this N8R8 part actually has.
FQBN="esp32:esp32:esp32s3:USBMode=hwcdc,CDCOnBoot=default,CPUFreq=240"
FQBN="$FQBN,FlashSize=8M,PartitionScheme=default_8MB,PSRAM=disabled"
FQBN="$FQBN,FlashMode=qio,JTAGAdapter=default"

DO_FLASH=0
SWITCHES=()
for arg in "$@"; do
    case "$arg" in
        --flash) DO_FLASH=1 ;;
        -D*)     SWITCHES+=("$arg") ;;
        *) echo "unknown argument: $arg" >&2; exit 2 ;;
    esac
done

case "$WORK" in
    *" "*) echo "build dir must not contain spaces: $WORK" >&2; exit 2 ;;
esac
rm -rf "$SKETCH"
mkdir -p "$SKETCH"
cp "$SRC"/*.c "$SRC"/*.h "$SKETCH"/

# Mirror firmware/main/CMakeLists.txt: the actor's weights are generated from a
# trained policy by scripts/verify_actor.py --export, and the inference code is
# compiled only when that header exists. Without this the sketch builds
# actor.c against no weights and -DRUN_ACTOR_BENCH=1 fails on the #error that
# is supposed to explain itself. The two toolchains must agree about this or a
# build succeeds on one and not the other for reasons nobody will look for.
ACTOR_FLAG=""
if [ -f "$SRC/sac_actor_weights.h" ]; then
    ACTOR_FLAG="-DHAVE_SAC_ACTOR=1"
    echo "  actor     weights found, inference included"
else
    rm -f "$SKETCH/actor.c" "$SKETCH/bench_actor.c"
    echo "  actor     no sac_actor_weights.h, inference omitted"
fi

cat > "$SKETCH/evpil_fw.ino" <<'INO'
/* Generated by scripts/arduino_build.sh. Do not edit; edit firmware/main/.
 *
 * The whole of the application is the IDF entry point, renamed by a -D so
 * that main.c does not have to know it is being built as a sketch. It starts
 * the pinned tasks and returns, exactly as it does under the IDF, and those
 * tasks then run independently of the Arduino loop task.
 */
extern "C" void evpil_app_main(void);

void setup()
{
    evpil_app_main();
}

void loop()
{
    /* Nothing to do here. The control and inference tasks are pinned to their
     * own cores by tasks_start(); this is the core's loop task and must not
     * take time away from them. */
    vTaskDelay(pdMS_TO_TICKS(1000));
}
INO

# The rename goes to the C compiler ONLY. The core's own app_main lives in
# cores/esp32/main.cpp, and applying the -D to C++ as well renames that too:
# the sketch then has two evpil_app_main and nothing named app_main for the
# prebuilt libfreertos to call. The switches are harmless either way and go to
# both, so a header shared with a .ino cannot see one half of a build.
COMMON=""
if [ ${#SWITCHES[@]} -gt 0 ]; then
    COMMON="${SWITCHES[*]}"
fi
C_EXTRA="-Dapp_main=evpil_app_main -I$SKETCH $ACTOR_FLAG $COMMON"
CPP_EXTRA="-I$SKETCH $ACTOR_FLAG $COMMON"

echo "arduino-cli build"
echo "  fqbn      $FQBN"
echo "  switches  ${SWITCHES[*]:-none}"
echo "  sketch    $SKETCH"

arduino-cli compile \
    --fqbn "$FQBN" \
    --build-path "$BUILD_PATH" \
    --build-property "compiler.c.extra_flags=$C_EXTRA" \
    --build-property "compiler.cpp.extra_flags=$CPP_EXTRA" \
    --build-property "compiler.optimization_flags=-O2" \
    "$SKETCH"

if [ "$DO_FLASH" = "1" ]; then
    echo "flashing $PORT"
    arduino-cli upload -p "$PORT" --fqbn "$FQBN" \
        --input-dir "$BUILD_PATH" "$SKETCH"
fi
